#ifndef B43OS9_H_
#define B43OS9_H_

#ifdef __MWERKS__
#pragma options align=power  /* same as the Tester/driver */
#endif

/*
 * b43os9.h - Interface of the AirPort Extreme driver for Mac OS 9.
 *
 * Underneath is the unmodified Linux 5.15 wireless stack: b43 (chip
 * driver), ssb (bus), mac80211 (MLME, encryption, rate control) and cfg80211
 * (scanning, connection, regulatory). This interface takes the place of
 * nl80211, i.e. of what "iw" and wpa_supplicant use on Linux:
 * commands are functions, events are callbacks.
 *
 * Data travels as Ethernet II frames (destination, source, type,
 * data): mac80211 does the conversion to/from 802.11.
 *
 * Standard C types only: can be included together with the Mac OS headers.
 */
#include "b43env.h"

typedef struct b43os9 b43os9;

/* Errors: negative errno values as in Linux */
#define B43OS9_OK               0
#define B43OS9_ERR_NODEV        (-19)
#define B43OS9_ERR_INVAL        (-22)
#define B43OS9_ERR_BUSY         (-16)
#define B43OS9_ERR_NOMEM        (-12)
#define B43OS9_ERR_NOTCONN      (-107)

/* Firmware built into the program (b43fw.c, generated by Tools/fw2c.py) */
typedef struct b43os9_firmware {
    const unsigned char *ucode;  unsigned long ucode_len;   /* b43/ucode5.fw */
    const unsigned char *pcm;    unsigned long pcm_len;     /* b43/pcm5.fw */
    const unsigned char *iv;     unsigned long iv_len;      /* b43/b0g0initvals5.fw */
    const unsigned char *bsiv;   unsigned long bsiv_len;    /* b43/b0g0bsinitvals5.fw */
} b43os9_firmware;

/* Events (cfg80211 -> Mac OS). Any pointer may be NULL. */
typedef struct b43os9_events {
    void *ctx;
    /* Scan finished: read the results with b43os9_scan_result() */
    void (*scan_done)(void *ctx, int aborted);
    /* Result of b43os9_connect(): status 0 = associated, otherwise an 802.11
     * status code (or -1 = no response) */
    void (*connect_result)(void *ctx, int status, const unsigned char *bssid);
    /* Connection lost or closed: reason = 802.11 reason code */
    void (*disconnected)(void *ctx, unsigned short reason, int from_ap);
    /* Ethernet II frame received (EAPOL too, type 0x888E) */
    void (*rx)(void *ctx, const unsigned char *frame, unsigned long len);
    /* Michael MIC failure (TKIP): for WPA countermeasures */
    void (*mic_failure)(void *ctx, const unsigned char *addr, int group);
    /* WPA handshake completed, keys installed, port open: data flows
     * from here on (only with b43os9_connect_psk) */
    void (*authorized)(void *ctx, const unsigned char *bssid);
} b43os9_events;

/* Network found by the scan (from the cfg80211 BSS table) */
typedef struct b43os9_bss {
    unsigned char bssid[6];
    unsigned char ssid[33];             /* zero-terminated */
    unsigned char ssid_len;
    unsigned char channel;
    int           signal_dbm;
    unsigned short capability;          /* bit 4 = privacy (WEP/WPA) */
    unsigned short beacon_interval;
    unsigned char ies[512];             /* information elements (RSN, WPA, ...) */
    unsigned short ies_len;
} b43os9_bss;

/* Hardware information (diagnostics) */
typedef struct b43os9_hwinfo {
    unsigned short chip_id, chip_rev, chip_pkg;
    unsigned short core_id, core_rev;
    unsigned short board_vendor, board_type, board_rev;
    unsigned char  phy_type, phy_rev, phy_analog;
    unsigned short radio_manuf, radio_ver, radio_rev;
    unsigned char  sprom_rev;
    unsigned short boardflags_lo, boardflags_hi;
    unsigned char  ant_available_bg;
    unsigned char  maxpwr_bg;
    unsigned short pa0b0, pa0b1, pa0b2;
    unsigned char  itssi_bg;
    unsigned char  mac[6];              /* interface address */
    unsigned short fw_rev, fw_patch, fw_hdr_format;
    int            desired_txpower;
    int            bbatt, rfatt, tx_control, tx_bias, tx_magn;
} b43os9_hwinfo;

/* Ciphers (as 802.11 WLAN_CIPHER_SUITE_*) */
#define B43OS9_CIPHER_WEP40     0x000FAC01UL
#define B43OS9_CIPHER_TKIP      0x000FAC02UL
#define B43OS9_CIPHER_CCMP      0x000FAC04UL
#define B43OS9_CIPHER_WEP104    0x000FAC05UL
#define B43OS9_CIPHER_AES_CMAC  0x000FAC06UL

/* Startup options (Linux module parameters) */
typedef struct b43os9_options {
    int verbose;            /* b43 verbose: 0 errors .. 3 debug (default 1) */
    int pr_debug;           /* 1 = ssb/mac80211/cfg80211 pr_debug messages */
    int hwcrypt;            /* 1 = hardware encryption (default, as Linux) */
    int qos;                /* 1 = QoS/WMM (default, as Linux) */
    const char *regdom;     /* ISO 3166 country ("IT", "US", ...); NULL = "00" */
} b43os9_options;

/* -------------------------------------------------------------------------
 * Startup and main loop
 * ------------------------------------------------------------------------- */

/* Starts the stack in kernel order (cfg80211, mac80211, ssb, b43),
 * loads the firmware and registers the "wlan0" interface. mmio = BAR0 already
 * mapped by Mac OS. opt may be NULL. */
int  b43os9_attach(b43os9 **out, volatile unsigned char *mmio, const b43_env *env,
                   const b43os9_firmware *fw, const b43os9_options *opt,
                   const b43os9_events *events);

/* Periodic work: chip interrupts (polled), work queues, timers.
 * Call often (every few ms) from the Tester loop or from the driver. */
void b43os9_poll(b43os9 *b);

/* Brings the interface up/down (ifconfig wlan0 up/down). mac = NULL for
 * the SPROM address. */
int  b43os9_up(b43os9 *b, const unsigned char *mac);
void b43os9_down(b43os9 *b);

void b43os9_get_hwinfo(b43os9 *b, b43os9_hwinfo *info);

/* -------------------------------------------------------------------------
 * Commands (as nl80211)
 * ------------------------------------------------------------------------- */

/* Scan on all allowed channels. ssid != NULL: active scan for
 * that network (in addition to the generic one). End: scan_done event. */
int  b43os9_scan(b43os9 *b, const char *ssid);
/* Result number idx (0, 1, ...): 1 = valid, 0 = no more */
int  b43os9_scan_result(b43os9 *b, unsigned int idx, b43os9_bss *out);

/* Connect (NL80211_CMD_CONNECT). bssid may be NULL. ie = elements
 * to add to the association request (wpa_supplicant's RSN/WPA IE),
 * NULL for an open network. privacy = 1 if the network is protected. */
int  b43os9_connect(b43os9 *b, const char *ssid, const unsigned char *bssid,
                    const unsigned char *ie, unsigned int ie_len, int privacy);
int  b43os9_disconnect(b43os9 *b, unsigned short reason);

/* Connect to a WPA/WPA2-PSK network with wpa_supplicant 2.11
 * (Common/wpa/os9/wpas_os9.c): the network must be in the scan
 * results. passphrase = 8..63 characters. Result: connect_result, then
 * authorized at the end of the 4-way handshake. */
int  b43os9_connect_psk(b43os9 *b, const char *ssid, const unsigned char *bssid,
                        const char *passphrase);

/* Keys (NL80211_CMD_NEW_KEY + SET_KEY). pairwise = 1 pairwise key
 * (mac = AP), 0 group key. seq = initial counter (RSC), may
 * be NULL. */
int  b43os9_add_key(b43os9 *b, int key_idx, int pairwise, const unsigned char *mac,
                    unsigned long cipher, const unsigned char *key, unsigned int key_len,
                    const unsigned char *seq, unsigned int seq_len);
/* 802.1X port authorized (NL80211_CMD_SET_STATION, AUTHORIZED flag) */
int  b43os9_authorize(b43os9 *b, const unsigned char *bssid);

/* Transmits an Ethernet II frame (dev_queue_xmit) */
int  b43os9_tx(b43os9 *b, const unsigned char *frame, unsigned long len);

/* Interface address */
void b43os9_get_mac(b43os9 *b, unsigned char *mac);

#ifdef __MWERKS__
#pragma options align=reset
#endif

#endif /* B43OS9_H_ */
